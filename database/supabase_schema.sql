-- Public Read Policies (Allow anyone to view products, categories, shops, courses, events)
CREATE POLICY "Allow public read access for categories" ON public.categories FOR SELECT USING (true);
CREATE POLICY "Allow public read access for shops" ON public.shops FOR SELECT USING (true);
CREATE POLICY "Allow public read access for products" ON public.products FOR SELECT USING (true);
CREATE POLICY "Allow public read access for courses" ON public.courses FOR SELECT USING (true);
CREATE POLICY "Allow public read access for events" ON public.events FOR SELECT USING (true);

-- Orders Policies (Allow users to insert orders & read their own orders)
CREATE POLICY "Allow anonymous and authenticated order creation" ON public.orders FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow users to view their own orders" ON public.orders FOR SELECT USING (
  auth.uid() = user_id OR auth.role() = 'service_role' OR user_id IS NULL
);

-- Profiles Policies
CREATE POLICY "Allow individual read of own profile" ON public.profiles FOR SELECT USING (auth.uid() = id);
CREATE POLICY "Allow individual update of own profile" ON public.profiles FOR UPDATE USING (auth.uid() = id);

-- ==============================================================================
-- AUTOMATIC PROFILE CREATION TRIGGER ON SUPABASE AUTH SIGNUP
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, full_name, email, role)
  VALUES (
    new.id,
    COALESCE(new.raw_user_meta_data->>'name', new.raw_user_meta_data->>'full_name', 'Customer'),
    new.email,
    'customer'
  );
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

