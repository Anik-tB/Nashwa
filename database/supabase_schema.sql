-- A. Automatic Profile Creator & Google OAuth Synchronizer
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
  extracted_name TEXT;
  extracted_avatar TEXT;
  extracted_provider TEXT;
BEGIN
  extracted_name := COALESCE(
    new.raw_user_meta_data->>'full_name',
    new.raw_user_meta_data->>'name',
    SPLIT_PART(new.email, '@', 1)
  );
  extracted_avatar := new.raw_user_meta_data->>'avatar_url';
  extracted_provider := COALESCE(new.raw_app_meta_data->>'provider', 'email');

  INSERT INTO public.profiles (id, full_name, email, avatar_url, role, guild_tier, patron_points, provider)
  VALUES (
    new.id,
    extracted_name,
    new.email,
    extracted_avatar,
    'customer',
    'Artisan Fellow',
    340,
    extracted_provider
  )
  ON CONFLICT (id) DO UPDATE SET
    full_name = EXCLUDED.full_name,
    avatar_url = COALESCE(EXCLUDED.avatar_url, public.profiles.avatar_url),
    updated_at = NOW();

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- B. Auto-Aggregate Product Rating & Count When Review Added
CREATE OR REPLACE FUNCTION public.update_product_rating_on_review()
RETURNS TRIGGER AS $$
DECLARE
  avg_score NUMERIC(3, 2);
  cnt INTEGER;
BEGIN
  SELECT ROUND(AVG(rating)::numeric, 2), COUNT(*)
  INTO avg_score, cnt
  FROM public.reviews
  WHERE product_id = NEW.product_id;

  UPDATE public.products
  SET rating = COALESCE(avg_score, 5.0),
      reviews_count = cnt
  WHERE id = NEW.product_id;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_review_added ON public.reviews;
CREATE TRIGGER on_review_added
  AFTER INSERT OR UPDATE OR DELETE ON public.reviews
  FOR EACH ROW EXECUTE FUNCTION public.update_product_rating_on_review();

