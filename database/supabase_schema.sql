-- PROFILES TABLE (Synchronized with Supabase Auth & Google OAuth)
CREATE TABLE public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name TEXT NOT NULL,
  email TEXT UNIQUE NOT NULL,
  avatar_url TEXT,
  role TEXT DEFAULT 'customer' CHECK (role IN ('customer', 'artisan', 'admin')),
  guild_tier TEXT DEFAULT 'Artisan Fellow' CHECK (guild_tier IN ('Apprentice Patron', 'Artisan Fellow', 'Grand Guild Patron')),
  patron_points INTEGER DEFAULT 340,
  provider TEXT DEFAULT 'email',
  phone TEXT,
  shipping_address TEXT,
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW()),
  updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

-- CATEGORIES TABLE
